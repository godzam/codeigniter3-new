/*
 * Starts every <table data-datatable> printed by datatable_table() as a
 * server-side DataTable. All configuration comes from data-* attributes
 * (set in PHP), so there is no inline script and nothing to copy per page.
 */
(function () {
	'use strict';

	if (!window.DataTable) { return; }

	// Don't pop the browser's alert() on a failed request; show a toast instead.
	DataTable.ext.errMode = 'none';

	var narrow = window.matchMedia('(max-width: 575.98px)').matches;

	document.querySelectorAll('table[data-datatable]').forEach(function (el) {
		var order = (el.getAttribute('data-order') || '').split(',');
		var columns = Array.prototype.map.call(el.querySelectorAll('thead th'), function (th) {
			return {
				orderable: th.getAttribute('data-orderable') !== 'false',
				className: th.getAttribute('data-class-name') || '',
				width: th.getAttribute('data-width') || null
			};
		});
		var search = el.getAttribute('data-search') !== '0';

		// data-filters="#box": inputs inside it are sent with every request and reload the table when changed.
		var filterBox = el.getAttribute('data-filters') ? document.querySelector(el.getAttribute('data-filters')) : null;

		var table = new DataTable(el, {
			serverSide: true,
			processing: true,
			responsive: true,
			ajax: {
				url: el.getAttribute('data-url'),
				type: 'GET',
				data: function (d) {
					if (!filterBox) { return; }
					filterBox.querySelectorAll('[name]').forEach(function (f) { d[f.name] = f.value; });
				}
			},
			columns: columns,
			order: order.length === 2 ? [[parseInt(order[0], 10), order[1]]] : [],
			pageLength: parseInt(el.getAttribute('data-page-length'), 10) || 10,
			lengthMenu: [10, 25, 50, 100],
			searchDelay: 400,
			// Fewer page buttons on phones so the pager never overflows.
			pagingType: narrow ? 'simple' : 'simple_numbers',
			layout: {
				topStart: 'pageLength',
				topEnd: search ? 'search' : null,
				bottomStart: 'info',
				bottomEnd: 'paging'
			},
			language: {
				search: '',
				searchPlaceholder: 'Search…',
				lengthMenu: '_MENU_',
				emptyTable: el.getAttribute('data-empty') || 'Nothing to show yet.',
				zeroRecords: 'No matching records',
				processing: '<span class="spinner-border spinner-border-sm" role="status" aria-label="Loading"></span>',
				info: '_START_–_END_ of _TOTAL_',
				infoEmpty: '0 records',
				infoFiltered: '(filtered from _MAX_)'
			}
		});

		if (filterBox) {
			filterBox.addEventListener('change', function () { table.ajax.reload(); });
		}

		table.on('dt-error', function () {
			if (window.App) { window.App.toast('error', 'Could not load the table. Reload the page and try again.'); }
		});

		// The search box and page-length select are generated by DataTables.
		var wrapper = el.closest('.dt-container');
		if (wrapper) {
			var input = wrapper.querySelector('.dt-search input');
			if (input) { input.setAttribute('aria-label', 'Search'); input.setAttribute('type', 'search'); input.setAttribute('enterkeyhint', 'search'); }
			var len = wrapper.querySelector('.dt-length select');
			if (len) { len.setAttribute('aria-label', 'Rows per page'); }
		}
	});
})();
